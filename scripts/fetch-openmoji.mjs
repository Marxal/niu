/*
 * Downloads the OpenMoji colour SVGs the catalogue actually uses.
 *
 * Why a script and not an npm package: the icon set is ~4,000 files and we need
 * fewer than a hundred of them. Pulling the whole package in to use 2% of it
 * would cost more than the rest of the app put together, and CLAUDE.md rules out
 * icon packages anyway. So this fetches exactly the emoji the seed catalogue
 * names, straight from OpenMoji's repository at a pinned release, and commits
 * them under public/openmoji/ — the build then needs no network at all.
 *
 * The files are written byte-for-byte as published. That is deliberate: OpenMoji
 * is CC BY-SA 4.0, and shipping the graphics unmodified keeps us clearly inside
 * "redistribute with credit" and out of "adapted material", which carries the
 * share-alike obligation. If we ever optimise or recolour them, that changes and
 * the note in docs/OPENMOJI.md needs revisiting.
 *
 * Run: node scripts/fetch-openmoji.mjs
 */

import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const HERE = dirname(fileURLToPath(import.meta.url))
const ROOT = resolve(HERE, '..')

/** Pinned so a re-run produces the same files, not whatever master is today. */
const RELEASE = '17.0.0'
const BASE = `https://raw.githubusercontent.com/hfg-gmuend/openmoji/${RELEASE}/color/svg`

const SEED = resolve(ROOT, 'src/lib/catalogue-seed.ts')
const OUT_DIR = resolve(ROOT, 'public/openmoji')
const OUT_MAP = resolve(ROOT, 'src/lib/openmoji.ts')

/** Every distinct emoji named in the seed catalogue. */
async function emojiInSeed() {
  const source = await readFile(SEED, 'utf8')
  const found = new Set()
  for (const match of source.matchAll(/emoji: '([^']+)'/g)) found.add(match[1])
  return [...found].sort()
}

/**
 * OpenMoji names a file after its codepoints, hyphen-joined. Emoji that carry a
 * variation selector are filed both ways depending on the character, so try the
 * full sequence first and then the one with FE0F dropped.
 */
function candidates(emoji) {
  const points = [...emoji].map((c) => c.codePointAt(0).toString(16).toUpperCase().padStart(4, '0'))
  const full = points.join('-')
  const bare = points.filter((p) => p !== 'FE0F').join('-')
  return full === bare ? [full] : [full, bare]
}

async function main() {
  const emoji = await emojiInSeed()
  await mkdir(OUT_DIR, { recursive: true })

  const map = []
  const missing = []
  let bytes = 0

  for (const glyph of emoji) {
    let saved = null
    for (const code of candidates(glyph)) {
      const response = await fetch(`${BASE}/${code}.svg`)
      if (!response.ok) continue
      const svg = await response.text()
      await writeFile(resolve(OUT_DIR, `${code}.svg`), svg, 'utf8')
      bytes += Buffer.byteLength(svg)
      saved = code
      break
    }
    if (saved) map.push([glyph, saved])
    else missing.push(glyph)
  }

  const lines = map.map(([glyph, code]) => `  '${glyph}': '${code}',`).join('\n')

  await writeFile(
    OUT_MAP,
    `/*
 * Which OpenMoji file draws which emoji.
 *
 * Generated by scripts/fetch-openmoji.mjs — do not edit by hand. Re-run the
 * script after adding an emoji to the catalogue seed.
 *
 * The values are filenames under public/openmoji/, which is OpenMoji's own
 * codepoint naming. Keeping the map explicit rather than computing codepoints at
 * runtime means a missing file is caught here, once, instead of showing up as a
 * broken image on someone's phone.
 *
 * OpenMoji ${RELEASE} — https://openmoji.org — CC BY-SA 4.0. See docs/OPENMOJI.md.
 */

/** Emoji character to OpenMoji filename stem. */
export const OPENMOJI: Readonly<Record<string, string>> = {
${lines}
}

/** Where the drawing for this emoji lives, or null if we don't ship one. */
export function openmojiSrc(emoji: string | null): string | null {
  if (!emoji) return null
  const code = OPENMOJI[emoji]
  return code ? \`\${import.meta.env.BASE_URL}openmoji/\${code}.svg\` : null
}

/** Every emoji we have a drawing for, in catalogue order. */
export const OPENMOJI_EMOJI: readonly string[] = Object.keys(OPENMOJI)
`,
    'utf8',
  )

  console.log(`OpenMoji ${RELEASE}: ${map.length} files, ${(bytes / 1024).toFixed(0)} kB`)
  if (missing.length) console.log(`No drawing for: ${missing.join(' ')}`)
}

await main()
